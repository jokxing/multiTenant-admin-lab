// Run with PLAYWRIGHT_MODULE pointing to an installed Playwright package.
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.DEMO_URL || 'http://127.0.0.1:9528';
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
    page.setDefaultTimeout(6000);
    const errors = [];
    page.on('pageerror', error => { errors.push(error.message); console.error('BROWSER ERROR', error.message); });
    await page.goto(`${base}/login`);
    await page.getByRole('button', { name: '管理员', exact: true }).click();
    await page.waitForTimeout(500);
    await page.goto(`${base}/demo/page-config`);
    await page.getByRole('button', { name: '新增页面', exact: true }).waitFor();
    await page.getByRole('button', { name: '新增页面', exact: true }).click();
    await page.getByRole('button', { name: '取消', exact: true }).click();
    await page.getByText('新增配置页面', { exact: true }).waitFor({ state: 'hidden' });
    assert.equal(await page.getByText('新增配置页面', { exact: true }).isVisible(), false);
    const initialHeight = await page.locator('textarea').first().evaluate(el => el.getBoundingClientRect().height);
    for (let i = 0; i < 3; i++) {
      await page.getByText('可视化', { exact: true }).first().click();
      await page.getByText('JSON', { exact: true }).first().click();
      await page.waitForTimeout(100);
      const height = await page.locator('textarea').first().evaluate(el => el.getBoundingClientRect().height);
      assert.ok(height > 400 && Math.abs(height - initialHeight) < 2);
    }
    assert.ok(await page.evaluate(() => localStorage.getItem('mtal_published_config')));
    console.log('PASS modal cancel and repeated JSON toggles');
    await page.getByRole('button', { name: '新增页面', exact: true }).click();
    const modal = page.locator('.n-modal');
    await modal.locator('.n-select').last().click();
    await page.locator('.n-base-select-option').filter({ hasText: '多语言素材组' }).click();
    assert.ok((await modal.innerText()).includes('仅表单') || (await modal.innerText()).includes('表单页'));
    await modal.getByRole('button', { name: '加入草稿', exact: true }).click();
    await page.getByText('新增配置页面', { exact: true }).waitFor({ state: 'hidden' });
    assert.equal(await page.getByText('新增配置页面', { exact: true }).isVisible(), false);
    // Select the form workspace if a newly created form opens with the table tab selected.
    const formTab = page.getByText('表单配置', { exact: true });
    if (await formTab.isVisible()) await formTab.click();
    const previewInput = page.getByPlaceholder('请输入标题');
    await previewInput.waitFor();
    await previewInput.fill('非法配置应保留的输入');
    await page.getByText('JSON Schema', { exact: true }).click();
    await page.locator('textarea').first().fill('[{"field":"bad","label":"Bad","type":"unknown"}]');
    await page.getByRole('button', { name: '应用 JSON', exact: true }).click();
    assert.equal(await previewInput.inputValue(), '非法配置应保留的输入');
    await page.getByRole('button', { name: '发布配置', exact: true }).click();
    await page.waitForTimeout(500);
    console.log('PASS new language template type, create, invalid JSON input retention and publish');
    await page.goto(`${base}/demo/runtime/content-recommend`);
    const rows = page.locator('tbody tr');
    await rows.first().waitFor();
    const ids = () => rows.locator('td:nth-child(2)').allTextContents();
    const original = await ids();
    await rows.nth(1).getByRole('button', { name: '置顶', exact: true }).click();
    await page.waitForTimeout(650);
    assert.equal((await ids())[0], original[1]);
    await page.reload();
    await rows.first().waitFor();
    assert.equal((await ids())[0], original[1]);
    const saved = await ids();
    await page.getByRole('switch').first().click();
    await rows.nth(1).getByRole('button', { name: '置顶', exact: true }).click();
    await page.waitForTimeout(650);
    assert.deepEqual(await ids(), saved);
    await page.getByPlaceholder('搜索标题或投放位置').fill('首页');
    await page.waitForTimeout(200);
    assert.equal(await rows.first().getByRole('button', { name: '下移', exact: true }).isDisabled(), true);
    await page.getByPlaceholder('搜索标题或投放位置').fill('');
    await page.waitForTimeout(150);
    // Use the actual drag handle, rather than invoking the action function directly.
    const beforeDrag = await ids();
    const from = await rows.nth(1).locator('.sort-drag-handle').boundingBox();
    const to = await rows.first().boundingBox();
    await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2);
    await page.mouse.down();
    await page.mouse.move(to.x + 20, to.y + 5, { steps: 20 });
    await page.waitForTimeout(250);
    await page.mouse.up();
    await page.waitForTimeout(650);
    assert.notDeepEqual(await ids(), beforeDrag);
    console.log('PASS sort button, reload, failure rollback, filter disable and mouse drag');
    await page.goto(`${base}/demo/runtime/lang-asset-form`);
    await page.getByRole('button', { name: '保存素材组', exact: true }).waitFor();
    await page.getByText('English', { exact: true }).click();
    await page.getByRole('button', { name: '保存素材组', exact: true }).click();
    await page.waitForTimeout(150);
    assert.equal(await page.getByText('简体中文标题必填', { exact: true }).isVisible(), true);
    await page.getByPlaceholder('请输入标题').fill('简体样例');
    await page.getByText('English', { exact: true }).click();
    await page.getByPlaceholder('可选说明，最多 120 字').fill('English description');
    await page.getByRole('button', { name: '保存素材组', exact: true }).click();
    await page.waitForTimeout(100);
    assert.equal(await page.getByText('已填写该语言内容时，标题必填', { exact: true }).isVisible(), true);
    await page.getByPlaceholder('请输入标题').fill('English sample');
    await page.getByRole('button', { name: '保存素材组', exact: true }).click();
    await page.waitForTimeout(600);
    await page.reload();
    await page.getByPlaceholder('请输入标题').waitFor();
    assert.equal(await page.getByPlaceholder('请输入标题').inputValue(), '简体样例');
    await page.getByRole('switch').first().click();
    await page.getByPlaceholder('请输入标题').fill('失败后保留');
    await page.getByRole('button', { name: '保存素材组', exact: true }).click();
    await page.waitForTimeout(550);
    assert.equal(await page.getByPlaceholder('请输入标题').inputValue(), '失败后保留');
    await page.reload();
    await page.getByPlaceholder('请输入标题').waitFor();
    assert.equal(await page.getByPlaceholder('请输入标题').inputValue(), '简体样例');
    console.log('PASS language error focus, switching, save refill and failure input retention');
    assert.deepEqual(errors, []);
    console.log('PASS no unhandled browser errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
